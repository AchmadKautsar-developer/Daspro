public class OperatorAssigment2 {
    public static void main(String[] args) {
      
        int a = 10;
        // Demonstrasi operator assignment
        a += 5; // a = a + 5
        System.out.println("Hasil a += 5: " + a);

        int b = 10;
        b -= 3; // b = b - 3
        System.out.println("Hasil b -= 3: " + b);

        int c = 10;
        c *= 5; // c = c * 5
        System.out.println("Hasil c *= 5: " + c);

        int d = 10;
        d /= 5; // d = d / 5
        System.out.println("Hasil d /= 5: " + d);

        int e = 10;
        e %= 5; // e = e % 5
        System.out.println("Hasil e %= 5: " + e);

    }
}
